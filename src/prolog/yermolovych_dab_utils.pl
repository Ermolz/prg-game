% ============================================================
% point_in_bounds/3
% ============================================================

% point_in_bounds(++Point, ++NX, ++NY) is semidet.
%
% Призначення:
%   Перевіряє, що точка Point = point(X, Y) належить межам ігрової сітки
%   розміру NX x NY, тобто:
%       0 =< X =< NX
%       0 =< Y =< NY
%
% Мультипризначенність:
%   1) point_in_bounds(++Point, ++NX, ++NY)
%      Єдине змістовне призначення:
%      перевірка належності конкретної точки межам поля.
%
%   Інші змістовні призначення відсутні:
%   - предикат не генерує точки поля;
%   - не призначений для відновлення NX, NY за точкою.
point_in_bounds(point(X, Y), NX, NY) :-
    X >= 0,
    X =< NX,
    Y >= 0,
    Y =< NY.

% ============================================================
% adjacent_points/2
% ============================================================

% adjacent_points(++Point, --Adj) is multi.
%
% Призначення:
%   Породжує всі точки Adj, що є сусідніми до Point по сітці,
%   тобто знаходяться на мангеттенській відстані 1:
%     - ліворуч,
%     - праворуч,
%     - зверху,
%     - знизу.
%
%   Межі поля тут не перевіряються: предикат описує лише геометричну
%   суміжність точок.
%
% Мультипризначенність:
%   1) adjacent_points(++Point, --Adj)
%      Основне змістовне призначення:
%      генерація всіх сусідніх точок для заданої точки.
%
%   Частково змістовним є також режим:
%   2) adjacent_points(++Point, +Adj)
%      як перевірка, чи є конкретна точка сусідньою.
%
%   Інші змістовні призначення відсутні:
%   - предикат не відновлює Point за Adj як окреме спеціальне призначення,
%     хоча формально уніфікація може це дозволяти.
adjacent_points(point(X, Y), point(Ax, Ay)) :-
    (   Ax is X - 1,
        Ay = Y
    ;   Ax is X + 1,
        Ay = Y
    ;   Ax = X,
        Ay is Y - 1
    ;   Ax = X,
        Ay is Y + 1
    ).

% ============================================================
% normalize_edge/2
% ============================================================

% normalize_edge(++EdgeIn, --EdgeOut) is det.
%
% Призначення:
%   Нормалізує ребро EdgeIn = edge(P1, P2), упорядковуючи його кінці
%   у стандартному порядку термів:
%       A @=< B
%
%   Це потрібно для того, щоб одне й те саме ребро не зберігалось
%   у двох різних напрямках.
%
% Мультипризначенність:
%   1) normalize_edge(++EdgeIn, --EdgeOut)
%      Основне змістовне призначення:
%      побудова канонічного запису ребра.
%
%   Частково змістовним є також режим:
%   2) normalize_edge(++EdgeIn, +EdgeOut)
%      як перевірка, що EdgeOut є правильною нормалізованою формою.
%
%   Інші змістовні призначення відсутні:
%   - предикат не генерує довільні ребра;
%   - не використовується для ненадійного зворотного відновлення EdgeIn.
normalize_edge(edge(P1, P2), edge(A, B)) :-
    (   P1 @=< P2
    ->  A = P1,
        B = P2
    ;   A = P2,
        B = P1
    ).

% ============================================================
% total_edges/3
% ============================================================

% total_edges(++NX, ++NY, --Total) is det.
%
% Призначення:
%   Обчислює загальну кількість ребер на сітці розміру NX x NY
%   за формулою:
%       NX * (NY + 1) + (NX + 1) * NY
%
%   Перша частина — горизонтальні ребра,
%   друга частина — вертикальні.
%
% Мультипризначенність:
%   1) total_edges(++NX, ++NY, --Total)
%      Основне змістовне призначення:
%      обчислення кількості ребер за відомими розмірами поля.
%
%   Частково змістовним є також режим:
%   2) total_edges(++NX, ++NY, +Total)
%      як перевірка наперед відомого результату.
%
%   Інші змістовні призначення відсутні:
%   - предикат не призначений для пошуку розмірів поля за Total.
total_edges(NX, NY, Total) :-
    Total is NX * (NY + 1) + (NX + 1) * NY.

% ============================================================
% other_player/2
% ============================================================

% other_player(++Player, --Other) is det.
%
% Призначення:
%   Для номера гравця 1 або 2 повертає номер іншого гравця.
%
% Мультипризначенність:
%   1) other_player(++Player, --Other)
%      Основне змістовне призначення:
%      отримати суперника поточного гравця.
%
%   Частково змістовним є також режим:
%   2) other_player(++Player, +Other)
%      як перевірка правильності відповідності.
%
%   3) other_player(--Player, ++Other)
%      теж є змістовним:
%      за відомим Other однозначно визначається Player.
%
%   4) other_player(--Player, --Other)
%      змістовне генераторне призначення:
%      породжує обидві допустимі пари гравців.
other_player(1, 2).
other_player(2, 1).

% ============================================================
% winner/3
% ============================================================

% winner(++S1, ++S2, --W) is det.
%
% Призначення:
%   Визначає результат гри за рахунками S1 і S2:
%     - W = 1, якщо перемагає перший гравець;
%     - W = 2, якщо перемагає другий гравець;
%     - W = 0, якщо нічия.
%
% Мультипризначенність:
%   1) winner(++S1, ++S2, --W)
%      Основне змістовне призначення:
%      визначити переможця за двома відомими рахунками.
%
%   Частково змістовним є також режим:
%   2) winner(++S1, ++S2, +W)
%      як перевірка наперед заданого результату.
%
%   Інші змістовні призначення відсутні:
%   - предикат не призначений для генерації всіх пар рахунків
%     за заданим W.
winner(S1, S2, 1) :-
    S1 > S2.

winner(S1, S2, 2) :-
    S2 > S1.

winner(S1, S2, 0) :-
    S1 =:= S2.